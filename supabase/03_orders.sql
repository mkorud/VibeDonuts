-- ---------- Tabel `orders` (PRD Bagian 5) ----------
create table if not exists public.orders (
  id                 bigint      generated by default as identity primary key,
  kode_pesanan       text        unique,                    -- VD-YYMM-id, diisi fungsi vd_create_order
  nama_pelanggan     text        not null check (char_length(btrim(nama_pelanggan)) between 3 and 100),
  no_hp              text        not null check (no_hp ~ '^[0-9]{10,15}$'),          -- PRD 4.4: minimal 10 angka
  alamat             text        not null check (char_length(btrim(alamat)) >= 10),
  catatan            text        not null default '',
  total_barang       integer     not null default 0 check (total_barang >= 0),
  ongkos_kirim       integer     not null default 0 check (ongkos_kirim >= 0),
  total_bayar        integer     not null default 0 check (total_bayar >= 0),
  status             text        not null default 'Menunggu Pembayaran'
                                 check (status in ('Menunggu Pembayaran','Menunggu Verifikasi',
                                                   'Diproses','Dikirim','Selesai','Dibatalkan')),
  url_bukti_transfer text,
  dibuat_pada        timestamptz not null default now(),
  diubah_pada        timestamptz not null default now()
);

create index if not exists orders_dibuat_idx on public.orders (dibuat_pada desc);
create index if not exists orders_status_idx on public.orders (status);
create index if not exists orders_no_hp_idx  on public.orders (no_hp);

-- ---------- Tabel `order_items` (harga & nama DIKUNCI, PRD 4.2) ----------
create table if not exists public.order_items (
  id           bigint  generated by default as identity primary key,
  order_id     bigint  not null references public.orders (id) on delete cascade,
  product_id   bigint  references public.products (id) on delete set null, -- nota tetap benar walau produk dihapus (PRD 5)
  nama_produk  text    not null,
  harga_satuan integer not null check (harga_satuan >= 0),
  jumlah       integer not null check (jumlah >= 1),
  subtotal     integer not null check (subtotal >= 0)
);

create index if not exists order_items_order_idx on public.order_items (order_id);

-- ---------- Tabel `stock_logs` (riwayat stok, PRD A-4) ----------
create table if not exists public.stock_logs (
  id           bigint      generated by default as identity primary key,
  product_id   bigint      references public.products (id) on delete cascade,
  perubahan    integer     not null,
  stok_sebelum integer     not null check (stok_sebelum >= 0),
  stok_sesudah integer     not null check (stok_sesudah >= 0),
  alasan       text        not null default '',
  user_id      bigint,
  dibuat_pada  timestamptz not null default now()
);

create index if not exists stock_logs_product_idx on public.stock_logs (product_id, dibuat_pada desc);

-- ---------- Tabel `settings` (PRD A-7) ----------
create table if not exists public.settings (
  kunci text primary key,
  nilai text not null default ''
);

