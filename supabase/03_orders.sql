-- Sumber : PRD Bagian 5 (Skema Data) + 4.1/4.2/4.3/4.4 (Logika Bisnis)
-- Target : Supabase (PostgreSQL) — jalankan SEKALI di SQL Editor,
--          SETELAH 01_products.sql dan 02_products_policies.sql.
